func servicePath() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, "Library", "Services", label+".workflow")
}

// The Quick Action writes a small .command file and opens it in Terminal,
// which avoids AppleScript quoting entirely.
func install(exe string) ([]string, string, error) {
	script := fmt.Sprintf(`HEAL=%s
for f in "$@"; do
  [ -d "$f" ] || f=$(dirname "$f")
  tmp="$(mktemp -d)/Run with LazyFinger.command"
  printf '#!/bin/bash\ncd %%q && exec %%q run --pause %%q\n' "$f" "$HEAL" "$f" > "$tmp"
  chmod +x "$tmp"
  open -a Terminal "$tmp"
done`, shQuote(exe))

	dir := filepath.Join(servicePath(), "Contents")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, "", err
	}
	if err := os.WriteFile(filepath.Join(dir, "Info.plist"), []byte(infoPlist), 0o644); err != nil {
		return nil, "", err
	}
	var esc strings.Builder
	_ = xml.EscapeText(&esc, []byte(script))
	wflow := strings.NewReplacer("{{SCRIPT}}", esc.String(), "{{U1}}", uuid(), "{{U2}}", uuid(), "{{U3}}", uuid()).Replace(documentWflow)
	if err := os.WriteFile(filepath.Join(dir, "document.wflow"), []byte(wflow), 0o644); err != nil {
		return nil, "", err
	}
	_ = exec.Command("/System/Library/CoreServices/pbs", "-update").Run()
	return []string{"Finder → right-click a folder → Quick Actions → " + label},
		"If it doesn't appear, turn it on in System Settings → Keyboard → Keyboard Shortcuts → Services → Files and Folders.", nil
}

func uninstall() ([]string, error) {
	if !exists(servicePath()) {
		return nil, nil
	}
	if err := os.RemoveAll(servicePath()); err != nil {
		return nil, err
	}
	_ = exec.Command("/System/Library/CoreServices/pbs", "-update").Run()
	return []string{"the Finder Quick Action"}, nil
}

func installed() []string {
	if exists(servicePath()) {
		return []string{"Finder Quick Action: " + servicePath()}
	}
	return nil
}

func uuid() string {
	b := make([]byte, 16)
	_, _ = rand.Read(b)
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	return strings.ToUpper(fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:]))
}

